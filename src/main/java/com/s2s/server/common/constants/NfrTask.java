package com.s2s.server.common.constants;

/**
 * 定时任务运行参数常量——<b>服务端单端正源</b>（任务只存在于服务端，Dart 端无消费方，
 * 例外登记同 {@link NfrObs}）。
 *
 * <p><b>为什么单独成类</b>：批次大小与迭代上限属「批次大小」这一硬纪律的管辖范围
 * （编码规范 §0.2：阈值/TTL/上限/超时/批次大小只引用常量名，禁写死数字）。
 * 它们散落在各任务类里看似只出现一次，但一旦要按实测调优就要满仓找——集中此处
 * 即为「一处可调」。</p>
 *
 * <p><b>依据源状态（如实标注）</b>：设计文档<b>未</b>规定这些批次参数（详设 §6 只给频率
 * 与约束，架构 §8 只给动作），故它们是编码期的防御性默认值——取「单批不至于长事务持锁、
 * 单次调度不至于无界耗时」的量级。若要按容量实测调整，改本类一处即可；
 * 该缺口的登记见说明文档 §2.9。</p>
 */
public final class NfrTask {

    /**
     * 私有构造器：常量类禁止实例化（范式同 {@code ErrorCode}）。
     */
    private NfrTask() {
    }

    /** 清理类任务的单批行数上限。分批的意义：一次性删除/更新大量行会长时间持锁并膨胀
     * undo（数据库设计 §6.5 对埋点表的同类告诫），故按小批推进。 */
    public static final int CLEANUP_BATCH_SIZE = 1000;

    /** 单次调度内最多迭代批数（安全上限）。防止「删除条件写错导致命中全表」时单次执行
     * 无界耗时占满调度线程；达到上限即停止并在日志中标注未收敛。 */
    public static final int CLEANUP_MAX_BATCHES = 100;

    /** 媒体孤儿清理的单批上限。该路径每行都要发一次 OSS 删除请求（网络往返），
     * 故批次小于纯数据库清理（避免单批耗时过长）。 */
    public static final int MEDIA_ORPHAN_BATCH_SIZE = 200;
}
