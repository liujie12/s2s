-- =============================================================================
-- V17__category_synonym.sql — 搜索词表（同义词 → 叶子类目）
-- =============================================================================
-- 出处口径：PRD §2.9/§2.10（同义词/拼音）、§6.4.1（搜索口径）；
--   地图语音语义搜索方案 U1（docs/plans/2026-10-24-0708-feat-map-voice-semantic-search-plan.md）。
-- 口径：
--   1. 一行 = 一个词条对映一个叶子类目；同一词条可对映多个叶子（如「租房」→ 20101/20102/20103）。
--   2. weight 越大优先级越高，供「同一段文本命中多个词条」时裁决；当前种子除专有词外统一 100。
--   3. pinyin 存首字母小写（如 zu fang → zf），供「zf」这类输入兜底。
--   4. 仅落确定性别称；方言/错别字长尾由运营后续补行，不改表结构。
-- 纯 DDL + 种子数据，无查询计划变更，EXPLAIN 结论豁免。
-- =============================================================================

DROP TABLE IF EXISTS `category_synonym`;
CREATE TABLE `category_synonym` (
  `id`               BIGINT      NOT NULL AUTO_INCREMENT COMMENT '词条 ID',
  `term`             VARCHAR(32) NOT NULL                COMMENT '词条（中文或拼音缩写）',
  `pinyin`           VARCHAR(64) NULL                    COMMENT '拼音首字母（小写，供字母输入兜底）',
  `leaf_category_id` INT         NOT NULL                COMMENT '目标叶子类目 ID（category.id，level=3）',
  `weight`           INT         NOT NULL DEFAULT 100    COMMENT '词条权重，越大越优先',
  `enabled`          TINYINT     NOT NULL DEFAULT 1      COMMENT '是否启用：1 启用 / 0 停用',
  `version`          INT         NOT NULL DEFAULT 1      COMMENT '词表版本号',
  `created_at`       DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_term_leaf` (`term`, `leaf_category_id`) COMMENT '同一词条对同一叶子只留一行',
  KEY `idx_term_enabled` (`term`, `enabled`)             COMMENT '按词条取启用行'
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci COMMENT = '搜索同义词表（确定性词表短路的唯一数据源）';

