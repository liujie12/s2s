-- V25 — 帖级凭证：一帖一证 → 一帖多证（2026-10-29）
--
-- 背景：资质挂载入口收敛到发布/编辑窗口的「资质栏」，同一条帖子可挂多张资质，
--   详情页按挂载顺序展示全部证名（无资质时整块不渲染）。
--   一帖一证由 uk_post 在结构上保证，本次改为「一帖一证一条记录」由
--   uk_post_cert(post_id, cert_id) 保证 —— 同一帖子重复挂同一张资质被结构拒绝，
--   不同资质可并存。
--
-- 兼容性：cert_id 可空（资质被删除后行内保留原 ID，读取侧按查不到 cert 行跳过）。
--   MySQL 唯一索引对 NULL 不去重，历史删除行不会与新行冲突。
--
-- 依据：用户裁定（2026-10-29）「发布记录追加资质只需在新增/编辑窗口末尾增加资质栏，
--   可添加多个；详情页资质栏动态展示」。
-- 纪律：已应用的迁移不可改，本文件为新增版本。
-- =============================================================================

ALTER TABLE `post_cert_declaration`
  DROP INDEX `uk_post`,
  ADD UNIQUE KEY `uk_post_cert` (`post_id`, `cert_id`) COMMENT '一帖一证一条记录：同一帖子可挂多张资质、同证不重复';
