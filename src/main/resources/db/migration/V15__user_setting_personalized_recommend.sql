-- 出处口径：
--   · 《个人信息保护法》第二十四条 / 《互联网信息服务算法推荐管理规定》第十七条：
--     向用户提供算法推荐服务的，应当告知并提供「关闭算法推荐服务」的选项；
--   · 2026-10-23 用户裁定：本期实现「关闭个性化排序」入口（B2-14 官网合规/
--     算法备案公示的前置）。
-- 口径：
--   · 1 = 开启（默认）：列表检索可用 `sort=composite`（时效 40 / 距离 40 / 完整度 20 加权）；
--   · 0 = 关闭：`sort=composite` 回落为 `distance`（仅按距离排序），其余显式排序不变；
--   · 与 `user_setting` 其余列同表：缺行 = 全默认（本列默认 1）。
--   · 1:1 与 `user`，不新增表；布尔列以 `TINYINT` 表（范式同 V6）。
-- EXPLAIN 结论：本迁移为纯 DDL（ALTER TABLE ADD COLUMN），无 SELECT/DML 查询语句，
--   EXPLAIN 不适用（编码规范 §2.2 要求的「无结论视为未完成」按此注明豁免）。
-- =============================================================================

ALTER TABLE `user_setting`
  ADD COLUMN `personalized_recommend` TINYINT NOT NULL DEFAULT 1
    COMMENT '个性化排序开关：1=开（综合加权），0=关（仅按距离排序）'
    AFTER `notify_cert`;
