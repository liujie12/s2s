-- V33__conversation_member_deleted_at.sql — 会话「仅自己删除」（2026-11-03）
-- =============================================================================
-- 出处口径：
--   · 2026-11-03 用户裁定：消息列表的每个会话可左滑删除，口径为「仅自己删除」——
--     只从当前用户的消息列表移除，对方不受影响；会话与消息数据仍保留（举报取证需要，
--     与 PRD §7.4.2 / §9.7「不物理删除」一致）。
--   · 再次收到新消息、或本人重新从详情页发起会话时，本列清空 → 会话重新可见。
-- 变更形态：conversation_member 新增 deleted_at（NULL=可见），存量行全部为 NULL，无需回填。
-- 配套改动：DELETE /conversations/{id}、列表/未读查询过滤、发送与开会话时恢复。
-- 回滚：直接 DROP COLUMN（该列只承载可见性，不影响既有已读水位口径）。
-- EXPLAIN 结论：纯 DDL（ALTER TABLE ADD COLUMN），无 SELECT/DML，EXPLAIN 不适用；
--   查询侧仍走既有 idx_user(user_id) 定位我的成员行，deleted_at 只做行内残差过滤，
--   单用户会话量为百级，不再新增复合索引（避免写放大）。
-- =============================================================================

ALTER TABLE `conversation_member`
    ADD COLUMN `deleted_at` DATETIME NULL DEFAULT NULL
        COMMENT '用户从自己列表删除会话的时刻：非空=对我不可见（仅本人口径，会话与消息保留；新消息或重新发起时清空）'
        AFTER `pushed_unread`;
