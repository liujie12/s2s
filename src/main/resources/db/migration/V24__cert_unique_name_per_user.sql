-- V24 — 同一用户的证书名不可重复（2026-10-28）
--
-- 背景：资质简化为「名称 + 图片」后，档案列表按证名识别；同一用户出现两条
--   同名资质既无法区分，也会让「详情只显示证名」失去辨识度。
--
-- 约束：cert(user_id, cert_name) 唯一。
--   * cert_name 为 NULL 的行不参与唯一（MySQL 唯一索引允许多个 NULL），
--     故个人实名（personal_realname）与未填证名的资质不受影响。
--   * 应用层先查重并回 40001，本索引作为并发兜底（写入冲突同样回 40001）。
--
-- 前置：V22 已加 cert_name 列；V23 已删除类型与有效期，不改动历史列。
-- 纪律：已应用的迁移不可改（V1–V23 保持原样），本文件为新增版本。
-- 若历史数据存在重名资质，本迁移会失败：请先人工改名或删除，再重新发版；
--   不要在迁移里自动改写用户数据。
-- =============================================================================

ALTER TABLE `cert`
  ADD UNIQUE KEY `uk_user_cert_name` (`user_id`, `cert_name`)
  COMMENT '同一用户证书名唯一（NULL 不参与）';
