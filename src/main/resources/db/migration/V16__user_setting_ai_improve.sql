-- =============================================================================
-- 出处口径：
--   · 《个人信息保护法》第十五条 / 第十七条：处理目的变更须告知，且应提供便捷的
--     撤回同意方式；《生成式人工智能服务管理暂行办法》第七条（数据来源合法性）；
--   · 《用户协议》9.4 与《隐私政策》第五条 / 第八条均对外承诺「你可在设置中关闭
--     AI 数据用于改进解析能力」——本迁移即为该承诺的落地载体。
-- 口径：
--   · 1 = 开启（默认）：允许将你确认/修改后的发布字段去标识化后用于改进解析能力；
--   · 0 = 关闭：不得将你的输入与结果用于模型优化（仅用于完成当次解析）。
--   · 当前 AI 语料沉淀（[152] `ai_parse_sample`）尚未开发；本列先作为偏好与未来
--     采样链路的强制过滤条件，避免功能上线时出现「无开关可关」的合规缺口。
--   · 与 `user_setting` 其余列同表：缺行 = 全默认；布尔列以 `TINYINT` 表（范式同 V6）。
-- EXPLAIN 结论：纯 DDL（ALTER TABLE ADD COLUMN），无 SELECT/DML，EXPLAIN 不适用
--   （编码规范 §2.2 的「无结论视为未完成」按此注明豁免）。
-- =============================================================================

ALTER TABLE `user_setting`
  ADD COLUMN `ai_improve_enabled` TINYINT NOT NULL DEFAULT 1
    COMMENT 'AI 数据用于改进解析：1=允许，0=关闭（仅用于当次解析）'
    AFTER `personalized_recommend`;
