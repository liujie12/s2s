#!/usr/bin/env bash
# ============================================================================
# S2S 门禁外壳库（四态记账 + 汇总 + 退出码结算）
# ----------------------------------------------------------------------------
# 依据：《核心概念》「闸门」词条 —— 必须有与通过/失败并列的第三态跳过
#       《核心概念》「可判定门禁」词条 —— 判据 + 卡点 + 失败后果三件套
#       《DevSecOps 接入方案》§3.1 三层门禁（L1/L2/L3）
#       《部署架构设计文档》§14.5 门禁的环境分级判定
#
# 本库只负责【外壳】，不含任何判据：
#   四态记账、SKIP 名单累积、汇总输出、退出码三档结算。
#   判据（查什么、怎么算合格）一律留在各门禁脚本自身。
#
# 抽出本库的原因不是「减少重复行数」，而是让外壳只有一份实现：
#   L2 部署门禁（gate-check.sh）与 L3 出包门禁（DevSecOps §4.4 的 11 步序列）
#   都需要同一套四态与同一组退出码。若各写一份，改了一处而漏改另一处时
#   两个门禁的「SKIP 是否阻塞」会悄悄不一致 —— 而这种不一致没有任何检出手段：
#   两边都能跑通、都打印绿色结论，差别只在退出码，而退出码没人盯着看。
#
# 用法：
#   GATE_LIB="$(dirname "${BASH_SOURCE[0]}")/gate-lib.sh"
#   [[ -f "${GATE_LIB}" ]] || { echo "[ERROR] 门禁外壳缺失" >&2; exit 1; }
#   source "${GATE_LIB}"  || { echo "[ERROR] 门禁外壳加载失败" >&2; exit 1; }
#   ...各判据调用 pass / fail / skip / not_applicable / manual_confirmed...
#   gate_conclude "环境：prod"      # 打印汇总并按三档 exit
#
# ⚠ 调用方必须显式检查 source 是否成功。本库缺失时若无检查，
#   在【不带 set -e】的门禁脚本里会是这样的后果：后续 pass/fail 全部
#   command not found（stderr 无人读），四个计数器保持 0，
#   gate_conclude 同样不存在，脚本以最后一条命令的退出码收尾、极可能是 0 ——
#   于是「门禁库不在」变成了「门禁全部通过」。
#   这与 G2「Dockerfile 不存在却报 PASS」是同一形态的假阴性，
#   只是发生在外壳层，波及全部检查项而非一项。
#
# ⚠ 本库刻意不含 set -e：门禁必须把所有检查项跑完再汇总。
#   set -e 会让第一个非 0 命令（判据里 grep 没匹配到就是非 0）终止整个脚本，
#   后面的项永远不被检查，而已跑过的项还都是 PASS —— 又一种绿灯假象。
#   调用方若自带 set -e，请自行确保判据分支的退出码被消费（如 `|| true`）。
# ============================================================================

# 四态计数器。source 时归零，故同一进程内不应重复 source。
GATE_PASS_COUNT=0
GATE_FAIL_COUNT=0
GATE_SKIP_COUNT=0
GATE_NA_COUNT=0

# SKIP 项名单，供汇总处逐条列出 —— 只报数字而不报是哪几项，
# 看的人无从判断「这次跳过的是否恰好是挡住核心风险的那一项」。
GATE_SKIP_ITEMS=""

# ---------------------------------------------------------------------------
# 函数：pass
# 功能：记录一项「已执行判定且结果合格」的检查，计入 GATE_PASS_COUNT
# 参数：$1 — 通过说明（须写明判定了什么，而非仅写「通过」）
# 返回：无返回值，副作用为递增 GATE_PASS_COUNT
# 说明：只有真正执行了判据、且拿到合格结论时才可调用。
#       「判不了」用 skip，「按环境没这个对象」用 not_applicable。
# ---------------------------------------------------------------------------
pass() { GATE_PASS_COUNT=$((GATE_PASS_COUNT + 1)); echo "  [PASS] $1"; }

# ---------------------------------------------------------------------------
# 函数：fail
# 功能：记录一项「已执行判定且结果不合格」的检查，计入 GATE_FAIL_COUNT
# 参数：$1 — 失败说明（须包含实际值与期望值，便于直接定位修复动作）
# 返回：无返回值，副作用为递增 GATE_FAIL_COUNT
# 说明：FAIL 无放行开关。调用方的 --gate-allow-skip 一类机制只对 SKIP 生效。
# ---------------------------------------------------------------------------
fail() { GATE_FAIL_COUNT=$((GATE_FAIL_COUNT + 1)); echo "  [FAIL] $1"; }

# ---------------------------------------------------------------------------
# 函数：skip
# 功能：记录一项「应当判定但本次未能判定」的检查，计入 GATE_SKIP_COUNT 并阻塞发版
# 参数：$1 — 检查项编号（如 G4）；$2 — 未能判定的原因（须写明缺什么前置条件）
# 返回：无返回值，副作用为递增 GATE_SKIP_COUNT 与追加 GATE_SKIP_ITEMS
# 说明：SKIP 不是 PASS 的温和版本。凡走到本函数，即表示该项风险状态未知，
#       退出码必须体现这一点，否则「没检查」与「检查通过」在调用方眼里等价。
# ---------------------------------------------------------------------------
skip() {
  GATE_SKIP_COUNT=$((GATE_SKIP_COUNT + 1))
  GATE_SKIP_ITEMS="${GATE_SKIP_ITEMS}
    - $1：$2"
  echo "  [SKIP] $2"
}

# ---------------------------------------------------------------------------
# 函数：not_applicable
# 功能：记录一项「按当前环境设计本就不存在」的检查，计入 GATE_NA_COUNT，不影响退出码
# 参数：$1 — 检查项编号（如 G7）；$2 — 不适用的原因（须说明该环境为何无此对象）
# 返回：无返回值，副作用为递增 GATE_NA_COUNT
# 说明：与 skip 的分界线是「有没有可判定的对象」——
#       dev 本地机没有云安全组，G7 无对象可判，是 N/A；
#       prod 上 docker 没装导致 G4 判不了，对象存在只是够不着，是 SKIP。
#       判据本身应在门禁自己的规格文档里按环境固化，
#       本函数不得用于临时豁免某项本该判定的检查 ——
#       一旦「不适用」可以随手声明，它就是个不留痕迹的放行开关。
# ---------------------------------------------------------------------------
not_applicable() {
  GATE_NA_COUNT=$((GATE_NA_COUNT + 1))
  echo "  [N/A ] $2"
}

# ---------------------------------------------------------------------------
# 函数：manual_confirmed
# 功能：判断某项人工确认项是否已由调用方通过 GATE_MANUAL_CONFIRMED 显式声明
# 参数：$1 — 检查项编号（如 G5）
# 返回：已声明返回 0，未声明返回 1
# 说明：环境变量格式为逗号分隔的编号列表，如 GATE_MANUAL_CONFIRMED="G5,G7"。
#       这个声明本身会随 stdout 进入发版留证，事后可追溯是谁在哪一次发版
#       声称做过人工验证 —— 这正是《DevSecOps》§3.2 四要素中的「留证方式」。
#       无条件为人工项记 PASS 是比 SKIP 更坏的做法：SKIP 至少留下了痕迹。
# ---------------------------------------------------------------------------
manual_confirmed() {
  local item="$1"
  [[ ",${GATE_MANUAL_CONFIRMED:-}," == *",${item},"* ]]
}

# ---------------------------------------------------------------------------
# 函数：gate_summary
# 功能：打印四态计数汇总与 SKIP 项逐条清单，不结算退出码
# 参数：$1 — 范围描述，追加在标题后（如「环境：prod」「产物：app-release.apk」）
# 返回：恒 0。退出码结算由 gate_exit_code / gate_conclude 负责
# 说明：拆出本函数是为了让需要在结算前追加动作的调用方（如 L3 出包门禁
#       第 10 步写 release-gate.log、第 11 步 FAIL 时删除产物 APK）
#       能先拿到汇总文本，再自行决定何时退出。
# ---------------------------------------------------------------------------
gate_summary() {
  local scope="${1:-}"
  echo ""
  echo "=========================================="
  echo "  门禁检查完成${scope:+（${scope}）}"
  echo "  PASS: ${GATE_PASS_COUNT}  |  FAIL: ${GATE_FAIL_COUNT}  |  SKIP: ${GATE_SKIP_COUNT}  |  N/A: ${GATE_NA_COUNT}"
  echo "=========================================="

  # SKIP 必须逐条列名。只报「SKIP: 3」，读日志的人无法判断跳掉的是否恰好是
  # 挡住核心风险的那一项 —— 而那一项往往就是最容易缺前置条件的一项。
  if [[ "${GATE_SKIP_COUNT}" -gt 0 ]]; then
    echo ""
    echo "  未判定项（既非通过也非不通过）：${GATE_SKIP_ITEMS}"
  fi
}

# ---------------------------------------------------------------------------
# 函数：gate_exit_code
# 功能：按四态计数算出应返回的退出码，向 stdout 输出 0 / 1 / 2
# 参数：无（读取 GATE_FAIL_COUNT / GATE_SKIP_COUNT）
# 返回：恒 0；结果通过 stdout 传出，供调用方写入留证日志后再退出
# 说明：三档不可合并。若把 SKIP 归入 0，调用方写 `if gate; then 发版`
#       就等于「没查过 = 可以发」。分出 2 之后，调用方仍可选择容忍
#       不完整判定，但必须【显式地】选择，并留下选择的痕迹。
# ---------------------------------------------------------------------------
gate_exit_code() {
  if [[ "${GATE_FAIL_COUNT}" -gt 0 ]]; then
    echo 1
  elif [[ "${GATE_SKIP_COUNT}" -gt 0 ]]; then
    echo 2
  else
    echo 0
  fi
}

# ---------------------------------------------------------------------------
# 函数：gate_conclude
# 功能：打印汇总与结论文案，并以三档退出码结束【当前脚本】
# 参数：$1 — 范围描述（同 gate_summary）
#       $2 — 可选，补齐 SKIP 前置条件的提示文案（各门禁的手段不同）
# 返回：不返回，直接 exit 0 / 1 / 2
# 说明：调用方若需在退出前追加动作（写留证日志、删除不合格产物），
#       不要用本函数，改用 gate_summary + gate_exit_code 自行结算。
# ---------------------------------------------------------------------------
gate_conclude() {
  local scope="${1:-}"
  local skip_hint="${2:-}"

  gate_summary "${scope}"

  local rc
  rc="$(gate_exit_code)"

  case "${rc}" in
    1)
      echo ""
      echo "  [结论] 阻塞：存在 ${GATE_FAIL_COUNT} 项 FAIL，请修复后重新检查"
      ;;
    2)
      echo ""
      echo "  [结论] 阻塞：无 FAIL，但有 ${GATE_SKIP_COUNT} 项未能判定。"
      echo "         「没有检查出问题」不等于「没有问题」。请补齐上列前置条件后重跑。"
      [[ -n "${skip_hint}" ]] && echo "         ${skip_hint}"
      ;;
    *)
      echo ""
      echo "  [结论] 全部 ${GATE_PASS_COUNT} 项判定通过（${GATE_NA_COUNT} 项按环境不适用），可以放行"
      ;;
  esac

  exit "${rc}"
}
