/// 距离文案（地图信息卡 / 叠点清单 / 列表卡片三处共用）。
///
/// 原先 `list_screen` 与 `map_screen` 各写一份同样的格式化分支，叠点清单是第三个
/// 消费方 —— 按编码规范 §1.1「第二处即上浮」，统一收在此处；三处任一处改了取整
/// 规则却漏改其它两处时，用户会看到同一条信息在列表写「368m」、在卡片写「370m」。
library;

/// 把「米」格式化成展示文案。
///
/// 1km 以内用米并**取整到 10m**：「368m」比「0.37km」更符合步行距离的直觉，
/// 且 1m 的精度对「走过去」这件事没有任何意义，反而显得嘈杂。
/// 超过 1km 用公里保留一位小数。
///
/// 参数：[meters] 距离（米），须为非负数。
/// 返回：如 `370m` / `1.2km`。
String distanceLabel(double meters) {
  if (meters < 1000) return '${(meters / 10).round() * 10}m';
  return '${(meters / 1000).toStringAsFixed(1)}km';
}
